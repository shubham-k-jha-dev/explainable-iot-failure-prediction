import { useState } from "react";
import { api, reportImage } from "../api.js";
import { Card, ErrorBox, Loading, PageHeader, useAsync } from "../components/common.jsx";
import ShapBars from "../components/ShapBars.jsx";

const FEATURE_NOTES = {
  "Air Temperature": "Ambient temperature around the machine. Strongly linked to heat-dissipation failures.",
  "Process Temperature": "Temperature of the machining process. A small gap to air temperature means poor heat dissipation.",
  "Tool Wear": "Minutes the current tool has been in use. Worn tools (200+ min) fail far more often.",
  "Torque": "Load on the spindle. Very high torque leads to overstrain and power failures.",
  "Rotational Speed": "Spindle speed. Combined with torque it determines mechanical power.",
  "Machine Type L": "Low-quality product variant — the most common and the most failure-prone.",
  "Machine Type M": "Medium-quality product variant.",
  "Machine Type H": "High-quality product variant — fewest failures.",
};

export default function Explainability() {
  const { data, loading, error } = useAsync(api.shapGlobal);
  const [selected, setSelected] = useState(null);

  if (loading) return <Loading />;
  if (error) return <ErrorBox error={error} />;

  const max = Math.max(...data.global.map((g) => g.importance));
  const total = data.global.reduce((s, g) => s + g.importance, 0);

  return (
    <>
      <PageHeader
        title="Explainability (SHAP)"
        subtitle="SHAP assigns each input feature a share of the credit for a prediction, so the model's decisions can be inspected and trusted."
      />

      <div className="grid two">
        <Card title="Global feature importance" subtitle="Mean |SHAP value| over the test set · click a feature to learn more">
          <div className="importance">
            {data.global.map((g, i) => (
              <button
                key={g.feature}
                className={`importance-row ${selected === g.feature ? "selected" : ""}`}
                onClick={() => setSelected(selected === g.feature ? null : g.feature)}
              >
                <span className="rank">{i + 1}</span>
                <span className="importance-label">{g.feature}</span>
                <span className="importance-track">
                  <span className="importance-bar" style={{ width: `${(g.importance / max) * 100}%` }} />
                </span>
                <span className="importance-value">{((g.importance / total) * 100).toFixed(1)}%</span>
              </button>
            ))}
          </div>
          {selected && (
            <div className="feature-note">
              <strong>{selected}</strong>
              <p>{FEATURE_NOTES[selected]}</p>
            </div>
          )}
        </Card>

        <Card title="How to read SHAP" className="explainer">
          <ol className="steps">
            <li>
              <strong>Start from the baseline.</strong> The average failure probability the model predicts over a background sample of
              training machines.
            </li>
            <li>
              <strong>Add each feature's contribution.</strong> A <span className="up">positive</span> SHAP value pushes the probability
              toward failure; a <span className="down">negative</span> value pushes it toward a healthy prediction.
            </li>
            <li>
              <strong>The sum is the prediction.</strong> Baseline + all contributions = this machine's failure probability.
            </li>
            <li>
              <strong>Global importance</strong> averages the size of those contributions across many machines to show which sensors
              matter most overall.
            </li>
          </ol>
          <p className="note">
            Try it live on the <a href="/predict">Predict &amp; Explain</a> page — every prediction comes with its own SHAP breakdown.
          </p>
        </Card>
      </div>

      <div className="grid two">
        <Card title="Local explanation example" subtitle="SHAP values for one sample test machine (feature values are standardised)">
          <ShapBars items={data.local} />
        </Card>
        <Card title="SHAP summary plot" subtitle="Generated by src/explainability/shap_explainer.py">
          <div className="report-image">
            <img src={reportImage("shap_global_importance.png")} alt="SHAP global importance plot" />
          </div>
        </Card>
      </div>
    </>
  );
}
